type StandardGenerated struct {
	JourneyScope  string            `json:"journeyScope"`
	JourneyTrace  string            `json:"journeyTrace"`
	EnrichedTrace string            `json:"enrichedTrace"`
	FutureTrace   string            `json:"futureTrace"`
	Epoch         string            `json:"epoch"`
	Trace         string            `json:"trace"`
	Hashes        map[string]string `json:"hashes"`
	Bodies        map[string][]byte `json:"-"`
}

// Extend the maintained fixture command; the source is ordinary OTLP JSON with
// nanosecond offsets. Generated bytes are preserved for exact replay.
func buildStandard(raw []byte, now time.Time) (StandardGenerated, error) {
	g := StandardGenerated{Epoch: now.UTC().Format(time.RFC3339Nano), Hashes: map[string]string{}, Bodies: map[string][]byte{}}
	var source map[string]json.RawMessage
	if err := json.Unmarshal(raw, &source); err != nil {
		return g, err
	}

	tr := ptraceotlp.NewExportRequest()
	ls := plogotlp.NewExportRequest()
	tb, _ := json.Marshal(map[string]json.RawMessage{"resourceSpans": source["resourceSpans"]})
	lb, _ := json.Marshal(map[string]json.RawMessage{"resourceLogs": source["resourceLogs"]})
	if err := tr.UnmarshalJSON(tb); err != nil {
		return g, err
	}
	if err := ls.UnmarshalJSON(lb); err != nil {
		return g, err
	}
	// OTLP uses hexadecimal IDs, unlike generic Protobuf JSON byte fields.
	var fresh pcommon.TraceID
	copy(fresh[:], diagnosticBytesID(16))
	g.Trace = hex.EncodeToString(fresh[:])
	epoch := pcommon.Timestamp(now.UnixNano())
	for i := 0; i < tr.Traces().ResourceSpans().Len(); i++ {
		r := tr.Traces().ResourceSpans().At(i)
		for j := 0; j < r.ScopeSpans().Len(); j++ {
			sp := r.ScopeSpans().At(j).Spans()
			for k := 0; k < sp.Len(); k++ {
				p := sp.At(k)
				p.SetTraceID(fresh)
				p.SetStartTimestamp(p.StartTimestamp() + epoch)
				if p.EndTimestamp() != 0 {
					p.SetEndTimestamp(p.EndTimestamp() + epoch)
				}
				for n := 0; n < p.Events().Len(); n++ {
					e := p.Events().At(n)
					e.SetTimestamp(e.Timestamp() + epoch)
				}
			}
		}
	}
	for i := 0; i < ls.Logs().ResourceLogs().Len(); i++ {
		r := ls.Logs().ResourceLogs().At(i)
		for j := 0; j < r.ScopeLogs().Len(); j++ {
			logs := r.ScopeLogs().At(j).LogRecords()
			for k := 0; k < logs.Len(); k++ {
				l := logs.At(k)
				l.SetTraceID(fresh)
				l.SetTimestamp(l.Timestamp() + epoch)
			}
		}
	}
	type wireRequest interface {
		MarshalProto() ([]byte, error)
		MarshalJSON() ([]byte, error)
	}
	for name, msg := range map[string]wireRequest{"standard-traces": tr, "standard-logs": ls} {
		b, err := msg.MarshalProto()
		if err != nil {
			return g, err
		}
		j, err := msg.MarshalJSON()
		if err != nil {
			return g, err
		}
		var zip bytes.Buffer
		w := gzip.NewWriter(&zip)
		w.Write(b)
		w.Close()
		for suffix, body := range map[string][]byte{".bin": b, ".json": j, ".bin.gz": zip.Bytes()} {
			key := name + suffix
			g.Bodies[key] = body
			h := sha256.Sum256(body)
			g.Hashes[key] = hex.EncodeToString(h[:])
		}
	}
	return g, nil
}
func generateStandard() error {
	raw, err := os.ReadFile("rest/fixtures/standard-otel.json")
	if err != nil {
		return err
	}
	g, err := buildStandard(raw, time.Now().Add(-time.Minute))
	if err != nil {
		return err
	}
	enriched, err := buildStandard(raw, time.Now().Add(-time.Minute))
	if err != nil {
		return err
	}
	future, err := buildStandard(raw, time.Now().Add(-time.Minute))
	if err != nil {
		return err
	}
	hintsRaw, err := os.ReadFile("rest/fixtures/standard-hints.json")
	if err != nil {
		return err
	}
	var hints struct {
		Spans  map[string]string `json:"spans"`
		Events map[string]string `json:"events"`
	}
	if err = json.Unmarshal(hintsRaw, &hints); err != nil {
		return err
	}
	for name, variant := range map[string]StandardGenerated{"standard-enriched": enriched, "standard-future": future} {
		q := ptraceotlp.NewExportRequest()
		if err = q.UnmarshalProto(variant.Bodies["standard-traces.bin"]); err != nil {
			return err
		}
		sp := q.Traces().ResourceSpans().At(0).ScopeSpans().At(0).Spans()
		for i := 0; i < sp.Len(); i++ {
			p := sp.At(i)
			if label := hints.Spans[p.Name()]; label != "" {
				p.Attributes().PutStr("stage.name", label)
			}
			for j := 0; j < p.Events().Len(); j++ {
				e := p.Events().At(j)
				if label := hints.Events[e.Name()]; label != "" {
					if name == "standard-future" && e.Name() == "retry.observed" {
						label = "changed.retry"
					}
					e.Attributes().PutStr("stage.name", label)
				}
			}
		}
		body, err := q.MarshalProto()
		if err != nil {
			return err
		}
		key := name + ".bin"
		g.Bodies[key] = body
		h := sha256.Sum256(body)
		g.Hashes[key] = hex.EncodeToString(h[:])
	}
	journeyBodies, journeyScope, journeyTrace, err := buildStandardJourney(time.Now().Add(-time.Minute))
	if err != nil {
		return err
	}
	for name, body := range journeyBodies {
		g.Bodies[name] = body
		h := sha256.Sum256(body)
		g.Hashes[name] = hex.EncodeToString(h[:])
	}
	g.JourneyScope = journeyScope
	g.JourneyTrace = journeyTrace
	g.EnrichedTrace = enriched.Trace
	g.FutureTrace = future.Trace
	if err = os.MkdirAll("rest/generated", 0700); err != nil {
		return err
	}
	for name, b := range g.Bodies {
		if err = os.WriteFile(filepath.Join("rest/generated", name), b, 0600); err != nil {
			return err
		}
	}
	pass, err := envRequired("SENTRAME_PASSPHRASE")
	if err != nil {
		return err
	}
	login, _ := json.Marshal(map[string]string{"passphrase": pass})
	if err = os.WriteFile("rest/generated/standard-login.json", login, 0600); err != nil {
		return err
	}
	token, err := envRequired("SENTRAME_SERVER_TOKEN")
	if err != nil {
		return err
	}
	browser, err := envRequired("SENTRAME_BROWSER_TOKEN")
	if err != nil {
		return err
	}
	values := map[string]string{"baseUrl": baseURL(), "serverToken": token, "browserToken": browser, "standardTrace": g.Trace, "enrichedTrace": g.EnrichedTrace, "futureTrace": g.FutureTrace, "journeyScope": g.JourneyScope, "journeyTrace": g.JourneyTrace}
	existing, err := os.ReadFile("rest/.env")
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	lines := []string{}
	for _, line := range strings.Split(strings.TrimSpace(string(existing)), "\n") {
		key, _, _ := strings.Cut(line, "=")
		if _, replace := values[key]; !replace && line != "" {
			lines = append(lines, line)
		}
	}
	for _, key := range []string{"baseUrl", "browserToken", "serverToken", "standardTrace", "enrichedTrace", "futureTrace", "journeyScope", "journeyTrace"} {
		lines = append(lines, key+"="+values[key])
	}
	if err = os.WriteFile("rest/.env", []byte(strings.Join(lines, "\n")+"\n"), 0600); err != nil {
		return err
	}
	b, _ := json.MarshalIndent(g, "", "  ")
	return os.WriteFile("rest/generated/standard-manifest.json", b, 0600)
}

func verifyStandard() error {
	raw, err := os.ReadFile("rest/generated/standard-manifest.json")
	if err != nil {
		return err
	}
	var g StandardGenerated
	if err = json.Unmarshal(raw, &g); err != nil {
		return err
	}
	token, err := envRequired("SENTRAME_SERVER_TOKEN")
	if err != nil {
		return err
	}
	for name, expected := range g.Hashes {
		b, err := os.ReadFile(filepath.Join("rest/generated", name))
		if err != nil {
			return err
		}
		h := sha256.Sum256(b)
		if hex.EncodeToString(h[:]) != expected {
			return errors.New("standard generated body changed; preserve exact replay bytes")
		}
	}
	browser, err := envRequired("SENTRAME_BROWSER_TOKEN")
	if err != nil {
		return err
	}
	requests, err := parseREST("rest/standard-otel.http", map[string]string{"baseUrl": baseURL(), "serverToken": token, "browserToken": browser, "standardTrace": g.Trace, "enrichedTrace": g.EnrichedTrace, "futureTrace": g.FutureTrace, "journeyScope": g.JourneyScope, "journeyTrace": g.JourneyTrace, "csrf": "__standard_csrf__", "standardDefinition": "__standard_definition__", "traceReference": "__trace_reference__"})
	if err != nil {
		return err
	}
	jar, _ := cookiejar.New(nil)
	client := &http.Client{Jar: jar, Timeout: 20 * time.Second}
	firstByTrace := map[string]any{}
	capturedDefinition := ""
	journeyDefinition := ""
	journeyReads := 0
	referenceChecked := false
	reads := 0
	meaningReads := 0
	csrf, definition := "", ""
	traceReference := ""
	for i, r := range requests {
		requestBody := r.Body
		if r.Headers.Get("Content-Type") == "application/json" {
			requestBody = bytes.ReplaceAll(requestBody, []byte("__standard_definition__"), []byte(definition))
		}
		req, err := http.NewRequest(r.Method, strings.ReplaceAll(strings.ReplaceAll(r.URL, "__trace_reference__", traceReference), "__standard_definition__", definition), bytes.NewReader(requestBody))
		if err != nil {
			return err
		}
		req.Header = r.Headers.Clone()
		for key, values := range req.Header {
			for i, v := range values {
				values[i] = strings.ReplaceAll(v, "__standard_csrf__", csrf)
			}
			req.Header[key] = values
		}
		c := client
		if r.NoCookies {
			c = &http.Client{Timeout: 20 * time.Second}
		}
		resp, err := c.Do(req)
		if err != nil {
			return err
		}
		body, err := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
		resp.Body.Close()
		if err != nil {
			return err
		}
		if resp.StatusCode != r.Expected {
			return fmt.Errorf("standard request%d %s status%d expected%d", i+1, req.URL.Path, resp.StatusCode, r.Expected)
		}
		if req.URL.Path == "/api/views" && r.Method == "POST" && r.Expected == 200 {
			var v struct {
				ID   int64  `json:"id"`
				Mode string `json:"mode"`
			}
			if err = json.Unmarshal(body, &v); err != nil {
				return err
			}
			if v.Mode == "trace" {
				traceReference = fmt.Sprint(v.ID)
			}
		}
		if req.URL.Path == "/api/login" && r.Expected == 200 {
			var v map[string]string
			json.Unmarshal(body, &v)
			csrf = v["csrf"]
		}
		if req.URL.Path == "/api/definitions" && r.Method == "POST" && r.Expected == 200 {
			var v struct {
				Version int64 `json:"version"`
			}
			json.Unmarshal(body, &v)
			definition = fmt.Sprint(v.Version)
			if r.Name == "Activate scoped voting definition" {
				journeyDefinition = definition
			}
			if capturedDefinition == "" {
				capturedDefinition = definition
			}
		}
		if req.URL.Path == "/api/preview" && r.Expected == 200 {
			var v struct {
				Conflict string         `json:"conflict"`
				Matches  map[string]int `json:"matches"`
			}
			if err = json.Unmarshal(body, &v); err != nil {
				return err
			}
			if v.Conflict != "" || v.Matches["vote.committed"] != 1 {
				return errors.New("owner meaning preview is not one carrier-specific trusted commitment")
			}
		}
		if req.URL.Path == "/api/traces/"+g.JourneyTrace && r.Expected == 200 {
			var d struct {
				Mode, Interpretation string
				Operations           []struct {
					DurationNs *string `json:"durationNs"`
				}
				Business []struct {
					Definition int64 `json:"definition"`
				}
			}
			if err = json.Unmarshal(body, &d); err != nil {
				return err
			}
			if d.Mode != "trace" || d.Interpretation != "reference pinned definition preview" || len(d.Operations) != 1 || d.Operations[0].DurationNs == nil || *d.Operations[0].DurationNs != "200000000" {
				return errors.New("native trace reference lost mode, duration or pinned interpretation")
			}
			for _, m := range d.Business {
				if fmt.Sprint(m.Definition) != journeyDefinition {
					return errors.New("trace reference changed captured definition")
				}
			}
		}
		if req.URL.Path == "/api/snapshot" && r.Method == "GET" {
			if err := checkStandardJourney(body, journeyDefinition, r.Name == "Completed scoped voting journey"); err != nil {
				return err
			}
			journeyReads++
		}
		if bytes.Contains(body, []byte("STRUCTURAL-PRIVATE-SENTINEL")) {
			return errors.New("standard privacy sentinel leaked")
		}
		if r.Method == "GET" && strings.HasPrefix(req.URL.Path, "/api/traces/") && r.Expected == 200 && !strings.HasSuffix(req.URL.Path, g.JourneyTrace) {
			var d map[string]any
			if err = json.Unmarshal(body, &d); err != nil {
				return err
			}
			ops, ok := d["operations"].([]any)
			if !ok || len(ops) != 5 || d["mode"] != "trace" || d["computation"] != "native-inclusive-v1" {
				return errors.New("standard trace native model missing")
			}
			wantLogs := 2
			if strings.TrimPrefix(req.URL.Path, "/api/traces/") != g.Trace {
				wantLogs = 0
			}
			if len(d["events"].([]any)) != 2 || len(d["logs"].([]any)) != wantLogs {
				return errors.New("standard contextual evidence missing")
			}
			for _, v := range ops {
				op := v.(map[string]any)
				e := op["evidence"].(map[string]any)
				if e["scope"] != "" || e["occurrence"] != "" {
					return errors.New("ordinary wire invented custom context")
				}
				switch e["name"] {
				case "POST /votes":
					if op["durationNs"] != "1000000001" || len(e["links"].([]any)) != 32 || e["omittedLinks"] != float64(2) {
						return errors.New("native timing/link bounds wrong")
					}
				case "missing.parent":
					if op["timing"] != "right-censored" || op["durationNs"] != nil {
						return errors.New("missing end became sample")
					}
				case "invalid.clock":
					if op["timing"] != "unavailable" || op["durationNs"] != nil {
						return errors.New("bad clock became sample")
					}
				}
			}
			if req.URL.Query().Get("previewDefinition") != "" {
				facts := 0
				for _, v := range d["business"].([]any) {
					b := v.(map[string]any)
					if b["goal"] == true {
						if b["stage"] != "Vote saved" || b["carrier"] != "span-event" || b["boundary"] != "event-time" {
							return errors.New("generic HTTP or intent became configured persistence evidence")
						}
						facts++
					}
				}
				if facts != 1 {
					return errors.New("expected exactly one configured trusted commitment")
				}
				meaningReads++
				fmt.Println("PASS explicit meaning preview: one trusted Vote saved, native operation timings separate; no history rewrite")
				continue
			}
			if trace := strings.TrimPrefix(req.URL.Path, "/api/traces/"); trace == g.EnrichedTrace || trace == g.FutureTrace {
				if trace == g.EnrichedTrace {
					if _, seen := firstByTrace[req.URL.Path]; !seen {
						found := false
						for _, v := range d["suggestions"].([]any) {
							if v.(map[string]any)["label"] == "voting.retry" {
								found = true
							}
						}
						if !found {
							return errors.New("unmapped emitted hint did not offer literal suggestion")
						}
					}
				}
				wantRetry := trace == g.FutureTrace
				retry := false
				goal := false
				for _, v := range d["business"].([]any) {
					m := v.(map[string]any)
					if m["goal"] == true {
						if m["stage"] != "Vote saved" {
							return errors.New("emitted voting label overrode Vote saved")
						}
						goal = true
					}
					if m["stage"] == "voting.retry" {
						retry = true
					}
				}
				if !goal || retry != wantRetry {
					return errors.New("literal hint acceptance changed historical meaning or failed future mapping")
				}
			}
			delete(d, "revision")
			delete(d, "suggestions")
			key := req.URL.Path
			if prior, ok := firstByTrace[key]; !ok {
				firstByTrace[key] = d
			} else if !reflect.DeepEqual(prior, d) {
				return errors.New("native structure/timing/capture interpretation changed after replay or new definition")
			}
			reads++
		}
		if req.URL.Path == "/api/views" && r.Method == "GET" {
			var views []struct {
				Definition int64  `json:"definition"`
				Name       string `json:"name"`
			}
			if err = json.Unmarshal(body, &views); err != nil {
				return err
			}
			for _, v := range views {
				if v.Name == "Standard voting capture" && fmt.Sprint(v.Definition) == capturedDefinition {
					referenceChecked = true
				}
			}
		}
		fmt.Printf("PASS standard %02d %s %s → %d\n", i+1, r.Method, req.URL.Path, resp.StatusCode)
	}
	if journeyReads < 2 {
		return errors.New("scoped journey durable reads not exercised")
	}
	if !referenceChecked {
		return errors.New("historical reference definition not preserved")
	}
	if meaningReads != 1 {
		return errors.New("configured meaning durable read not exercised")
	}
	if reads < 2 {
		return errors.New("standard REST lacks replay reads")
	}
	fmt.Println("PASS native timing/links/events/log context and exact replay via actual durable protected reads; wire only.")
	return nil
}
